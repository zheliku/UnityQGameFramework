using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading.Tasks;
using UnityEditor;
using UnityEngine;
using UnityEngine.Networking;
using UnityQGameFramework.Runtime;
using Debug = UnityEngine.Debug;

namespace UnityQGameFramework.Editor
{
    /// <summary>
    /// 使用官方 Luban 编译器生成数据表。
    /// </summary>
    public static class LubanGenerator
    {
        /// <summary>
        /// Luban 编译器版本。
        /// </summary>
        public const string Version = "5.1.0";

        /// <summary>
        /// 编译器下载包的 SHA256 校验值。
        /// </summary>
        public const string ArchiveHash = "bac9a1b8d69cfeaa7ef1d8c67b34a007324d1cd158e0b14294521b3879ba5213";

        /// <summary>
        /// 生成代码的文件头。
        /// </summary>
        public const string GeneratedHeader = "// <auto-generated> QGF/Luban. Do not edit. </auto-generated>\n";

        /// <summary>
        /// 获取是否正在安装或生成。
        /// </summary>
        public static bool IsBusy { get; private set; }

        /// <summary>
        /// 获取最近一次编译器输出。
        /// </summary>
        public static string LastLog
        {
            get
            {
                return SessionState.GetString("QGF.Luban.LastLog", string.Empty);
            }

            private set
            {
                SessionState.SetString("QGF.Luban.LastLog", value ?? string.Empty);
            }
        }

        /// <summary>
        /// 获取编译器缓存目录。
        /// </summary>
        public static string CacheRoot
        {
            get
            {
                return Path.GetFullPath("Library/UnityQGameFramework/Tools/Luban/" + Version);
            }
        }

        /// <summary>
        /// 获取下载的编译器路径。
        /// </summary>
        public static string DefaultGenerator
        {
            get
            {
                return Path.Combine(CacheRoot, "Luban/Luban.dll");
            }
        }

        /// <summary>
        /// 获取或设置编译器进程的超时秒数。
        /// </summary>
        public static int ProcessTimeoutSeconds
        {
            get
            {
                return EditorPrefs.GetInt("QGF.Luban.Timeout." + Application.dataPath, 300);
            }

            set
            {
                if (value < 10 || value > 3600)
                {
                    throw new ArgumentOutOfRangeException(nameof(value), "Use a timeout between 10 and 3600 seconds.");
                }

                EditorPrefs.SetInt("QGF.Luban.Timeout." + Application.dataPath, value);
            }
        }

        /// <summary>
        /// 获取 QGF 包的实际目录。
        /// </summary>
        public static string PackageRoot
        {
            get
            {
                return UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(LubanGenerator).Assembly).resolvedPath;
            }
        }

        /// <summary>
        /// 获取项目内的目录路径。
        /// </summary>
        /// <param name="folder">目录资产。</param>
        /// <returns>相对于项目的目录路径。</returns>
        public static string FolderPath(DefaultAsset folder)
        {
            string path = AssetDatabase.GetAssetPath(folder);
            if (string.IsNullOrEmpty(path) || !path.StartsWith("Assets/", StringComparison.Ordinal) || !AssetDatabase.IsValidFolder(path))
            {
                throw new InvalidOperationException("Select a project folder inside Assets.");
            }

            return path;
        }

        /// <summary>
        /// 获取生成配置引用的 Luban 文件路径。
        /// </summary>
        /// <param name="profile">生成配置。</param>
        /// <returns>项目内的配置文件路径。</returns>
        public static string ConfigurationPath(LubanProfile profile)
        {
            if (profile == null)
            {
                throw new ArgumentNullException(nameof(profile));
            }

            profile.UpgradeConfiguration();
            string path = AssetDatabase.GetAssetPath(profile.ConfigurationFile);
            if (!path.StartsWith("Assets/", StringComparison.Ordinal) || !File.Exists(path))
            {
                throw new FileNotFoundException("Assign a luban.conf file inside Assets to the Luban Profile.", path);
            }

            return path;
        }

        /// <summary>
        /// 获取 Luban 配置指定的数据源目录。
        /// </summary>
        /// <param name="profile">生成配置。</param>
        /// <returns>相对于项目的源表目录。</returns>
        public static string SourcePath(LubanProfile profile)
        {
            string conf = ConfigurationPath(profile);
            var configuration = JsonUtility.FromJson<SourceConfiguration>(File.ReadAllText(conf));
            string source = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(conf), configuration.dataDir ?? "."));
            string assets = Path.GetFullPath(Application.dataPath);
            string project = Path.GetDirectoryName(assets) + Path.DirectorySeparatorChar;
            if (!source.StartsWith(assets + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase) || !Directory.Exists(source))
            {
                throw new DirectoryNotFoundException("The dataDir in luban.conf must reference a folder inside Assets: " + source);
            }

            return source.Substring(project.Length).Replace('\\', '/');
        }

        /// <summary>
        /// 读取 luban.conf 中的数据源位置。
        /// </summary>
        [Serializable]
        private sealed class SourceConfiguration
        {
            /// <summary>
            /// 数据文件相对配置文件的目录。
            /// </summary>
            public string dataDir = null;
        }

        /// <summary>
        /// 下载并校验官方 Luban 编译器。
        /// </summary>
        /// <returns>安装任务。</returns>
        public static async Task InstallAsync()
        {
            if (IsBusy)
            {
                throw new InvalidOperationException("Luban is busy.");
            }

            IsBusy = true;
            EditorApplication.LockReloadAssemblies();
            try
            {
                Directory.CreateDirectory(CacheRoot);
                string archive = Path.Combine(CacheRoot, "Luban.7z");
                if (!File.Exists(archive) || Hash(File.ReadAllBytes(archive)) != ArchiveHash)
                {
                    string download = archive + ".download";
                    using (var request = UnityWebRequest.Get("https://github.com/focus-creative-games/luban/releases/download/v" + Version + "/Luban.7z"))
                    {
                        request.downloadHandler = new DownloadHandlerFile(download);
                        request.timeout = 120;
                        var operation = request.SendWebRequest();
                        while (!operation.isDone)
                        {
                            await Task.Delay(100);
                        }

                        if (request.result != UnityWebRequest.Result.Success)
                        {
                            throw new IOException(request.error);
                        }
                    }

                    if (Hash(File.ReadAllBytes(download)) != ArchiveHash)
                    {
                        throw new IOException("Luban download checksum mismatch.");
                    }

                    File.Copy(download, archive, true);
                    File.Delete(download);
                }

                // Windows 和 macOS 自带的 bsdtar 支持 7z；Linux 需要安装 libarchive 的 bsdtar。
                await RunProcess("tar", new[] { "-xf", archive, "-C", CacheRoot }, CacheRoot);
                if (!File.Exists(DefaultGenerator))
                {
                    throw new IOException("Luban.dll was not extracted. Install a tar executable with 7z support and generate again. Required Luban version: " + Version + ".");
                }

                LastLog = "Luban " + Version + " installed in " + CacheRoot;
            }
            finally
            {
                IsBusy = false;
                EditorApplication.UnlockReloadAssemblies();
            }
        }

        /// <summary>
        /// 按指定配置生成或校验数据表。
        /// </summary>
        /// <param name="profile">生成配置。</param>
        /// <param name="validateOnly">是否只校验输入，不更新生成文件。</param>
        /// <returns>生成或校验任务。</returns>
        public static async Task GenerateAsync(LubanProfile profile, bool validateOnly = false)
        {
            if (IsBusy)
            {
                throw new InvalidOperationException("Luban is busy.");
            }

            if (profile == null)
            {
                throw new ArgumentNullException(nameof(profile));
            }

            if (EditorApplication.isPlayingOrWillChangePlaymode)
            {
                throw new InvalidOperationException("Stop Play Mode before generating configuration.");
            }

            string profilePath = AssetDatabase.GetAssetPath(profile);
            if (string.IsNullOrEmpty(profilePath) || !profilePath.StartsWith("Assets/", StringComparison.Ordinal))
            {
                throw new InvalidOperationException("Save the Luban Profile inside Assets before generating configuration.");
            }

            string source = SourcePath(profile);
            string code = FolderPath(profile.CodeFolder);
            string data = FolderPath(profile.DataFolder);
            string codeGuid = AssetDatabase.AssetPathToGUID(code);
            string dataGuid = AssetDatabase.AssetPathToGUID(data);
            List<string> ownedCode = profile.GeneratedCodeFolderGuid == codeGuid ? profile.GeneratedCodeFiles : new List<string>();
            List<string> ownedData = profile.GeneratedDataFolderGuid == dataGuid ? profile.GeneratedDataFiles : new List<string>();
            if (!validateOnly && profile.GeneratedDataFolderGuid != dataGuid && File.Exists(data + "/Catalog.asset"))
            {
                throw new IOException("Generation would overwrite an unowned catalog: " + data + "/Catalog.asset");
            }

            string[] paths =
            {
                source,
                code,
                data
            };
            for (int i = 0; i < paths.Length; ++i)
            {
                for (int j = i + 1; j < paths.Length; ++j)
                {
                    if (Overlaps(paths[i], paths[j]))
                    {
                        throw new InvalidOperationException("Source, C# and data folders must be separate, without nesting.");
                    }
                }
            }

            string conf = Path.GetFullPath(ConfigurationPath(profile));
            if (string.IsNullOrWhiteSpace(profile.Target))
            {
                throw new InvalidOperationException("A Luban target is required.");
            }

            if (!File.Exists(DefaultGenerator))
            {
                await InstallAsync();
            }

            string compiler = DefaultGenerator;

            if (!validateOnly && File.Exists(data + "/Catalog.asset") && AssetDatabase.LoadAssetAtPath<LubanDataTableCatalog>(data + "/Catalog.asset") == null)
            {
                throw new IOException("Catalog path is occupied by an invalid asset: " + data + "/Catalog.asset");
            }

            IsBusy = true;
            EditorApplication.LockReloadAssemblies();
            string stage = Path.GetFullPath("Library/UnityQGameFramework/Luban/Staging/" + Guid.NewGuid().ToString("N"));
            bool preserveStage = false;
            try
            {
                // Luban's CommandLine parser returns 1 for the informational --version option.
                string version = await RunProcess("dotnet", new[] { compiler, "--version" }, Path.GetDirectoryName(compiler), 1);
                if (!version.StartsWith("Luban " + Version + "+", StringComparison.Ordinal))
                {
                    throw new InvalidOperationException("Expected Luban " + Version + "; got " + version.Trim());
                }

                Directory.CreateDirectory(stage);
                var args = new List<string>
                {
                    compiler,
                    "--conf",
                    conf,
                    "-t",
                    profile.Target,
                    "--strict"
                };
                if (validateOnly)
                {
                    args.Add("-f");
                }
                else
                {
                    args.AddRange(new[] { "-c", "cs-bin", "-d", "bin", "--customTemplateDir", Path.Combine(PackageRoot, "Editor/Luban/Templates~"), "-x", "outputCodeDir=" + Path.Combine(stage, "Code"), "-x", "outputDataDir=" + Path.Combine(stage, "Data") });
                }

                LastLog = await RunProcess("dotnet", args, Path.GetDirectoryName(compiler));
                if (validateOnly)
                {
                    Debug.Log("Luban validation succeeded.");
                    return;
                }

                string schemaHash = PrepareCode(Path.Combine(stage, "Code"));
                CheckSync(Path.Combine(stage, "Code"), code, ownedCode, ".cs");
                CheckSync(Path.Combine(stage, "Data"), data, ownedData, ".bytes");
                var affected = OutputPaths(Path.Combine(stage, "Code"), code, ownedCode, ".cs").Concat(OutputPaths(Path.Combine(stage, "Data"), data, ownedData, ".bytes")).Concat(new[] { data + "/Catalog.asset", profilePath });
                var transaction = new LubanOutputTransaction(Path.Combine(stage, "Backup"), profile, affected, new[] { code, data, Path.GetDirectoryName(profilePath) });
                try
                {
                    AssetDatabase.DisallowAutoRefresh();
                    try
                    {
                        Sync(Path.Combine(stage, "Code"), code, ownedCode, ".cs");
                        Sync(Path.Combine(stage, "Data"), data, ownedData, ".bytes");
                        profile.GeneratedCodeFiles = ownedCode;
                        profile.GeneratedDataFiles = ownedData;
                        profile.GeneratedCodeFolderGuid = codeGuid;
                        profile.GeneratedDataFolderGuid = dataGuid;
                        EditorUtility.SetDirty(profile);
                        AssetDatabase.SaveAssetIfDirty(profile);
                    }
                    finally
                    {
                        AssetDatabase.AllowAutoRefresh();
                    }

                    AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
                    WriteCatalog(data, schemaHash, profile.GeneratedDataFiles);
                }
                catch (Exception failure)
                {
                    try
                    {
                        transaction.Rollback();
                    }
                    catch (Exception rollbackFailure)
                    {
                        preserveStage = true;
                        throw new AggregateException("Generation failed and recovery was incomplete. Backups retained at " + stage, failure, rollbackFailure);
                    }

                    throw;
                }

                Debug.Log("Luban generated configuration: " + AssetDatabase.GetAssetPath(profile));
            }
            catch (Exception exception)
            {
                LastLog += "\n" + exception.Message;
                throw;
            }
            finally
            {
                IsBusy = false;
                // Staging is a task-owned directory under Library, never an arbitrary profile path.
                try
                {
                    if (!preserveStage && Directory.Exists(stage))
                    {
                        Directory.Delete(stage, true);
                    }
                }
                finally
                {
                    EditorApplication.UnlockReloadAssemblies();
                }
            }
        }

        /// <summary>
        /// 检查两个目录是否相同或互为父子目录。
        /// </summary>
        /// <param name="left">第一个规范化目录。</param>
        /// <param name="right">第二个规范化目录。</param>
        /// <returns>两个目录是否重叠。</returns>
        private static bool Overlaps(string left, string right)
        {
            return left.Equals(right, StringComparison.OrdinalIgnoreCase) || left.StartsWith(right + "/", StringComparison.OrdinalIgnoreCase) || right.StartsWith(left + "/", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// 补充生成文件头并计算表结构版本。
        /// </summary>
        /// <param name="directory">编译器生成的代码目录。</param>
        /// <returns>表结构的 SHA256 标识。</returns>
        public static string PrepareCode(string directory)
        {
            string[] files = Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories).OrderBy(p => p, StringComparer.Ordinal).ToArray();
            if (files.Length == 0)
            {
                throw new IOException("Luban produced no C# files.");
            }

            var fingerprint = new StringBuilder();
            foreach (string file in files)
            {
                string[] lines = File.ReadAllText(file).Replace("\r\n", "\n").Split('\n');
                for (int i = 0; i < lines.Length; i++)
                {
                    lines[i] = lines[i].TrimEnd();
                }

                string text = GeneratedHeader + string.Join("\n", lines).TrimEnd() + "\n";
                File.WriteAllText(file, text, new UTF8Encoding(false));
                fingerprint.Append(file.Substring(directory.Length).Replace('\\', '/')).Append('\n').Append(text);
            }

            string hash = Hash(Encoding.UTF8.GetBytes(fingerprint.ToString()));
            foreach (string file in files)
            {
                File.WriteAllText(file, File.ReadAllText(file).Replace("__QGF_SCHEMA_HASH__", hash), new UTF8Encoding(false));
            }

            return hash;
        }

        /// <summary>
        /// 检查生成结果是否会覆盖非生成文件。
        /// </summary>
        /// <param name="source">本次生成文件的临时目录。</param>
        /// <param name="destination">项目中的输出目录。</param>
        /// <param name="owned">上次生成时登记的相对文件路径。</param>
        /// <param name="extension">受管理文件的扩展名。</param>
        private static void CheckSync(string source, string destination, List<string> owned, string extension)
        {
            foreach (string file in Directory.GetFiles(source, "*" + extension, SearchOption.AllDirectories))
            {
                string relative = file.Substring(source.Length + 1).Replace('\\', '/');
                string target = Path.Combine(destination, relative);
                if (Directory.Exists(target))
                {
                    throw new IOException("Generated file path is occupied by a directory: " + target);
                }

                if (File.Exists(target) && !owned.Contains(relative))
                {
                    throw new IOException("Generation would overwrite an unowned file: " + target);
                }
            }

            foreach (string relative in owned)
            {
                OwnedPath(destination, relative, extension);
            }
        }

        /// <summary>
        /// 收集本次同步可能写入或删除的文件路径。
        /// </summary>
        /// <param name="source">本次生成文件的临时目录。</param>
        /// <param name="destination">项目中的输出目录。</param>
        /// <param name="owned">上次生成时登记的相对文件路径。</param>
        /// <param name="extension">受管理文件的扩展名。</param>
        /// <returns>新旧生成文件的完整路径集合。</returns>
        private static IEnumerable<string> OutputPaths(string source, string destination, IEnumerable<string> owned, string extension)
        {
            return Directory.GetFiles(source, "*" + extension, SearchOption.AllDirectories).Select(file => OwnedPath(destination, file.Substring(source.Length + 1), extension)).Concat(owned.Select(relative => OwnedPath(destination, relative, extension))).Distinct(StringComparer.OrdinalIgnoreCase);
        }

        /// <summary>
        /// 解析并检查受管理的生成文件路径。
        /// </summary>
        /// <param name="directory">输出根目录。</param>
        /// <param name="relative">已登记的相对文件路径。</param>
        /// <param name="extension">允许的文件扩展名。</param>
        /// <returns>位于输出根目录内且扩展名匹配的完整路径。</returns>
        private static string OwnedPath(string directory, string relative, string extension)
        {
            string root = Path.GetFullPath(directory) + Path.DirectorySeparatorChar;
            string full = Path.GetFullPath(Path.Combine(directory, relative));
            if (!full.StartsWith(root, StringComparison.OrdinalIgnoreCase) || Path.GetExtension(full) != extension)
            {
                throw new IOException("Invalid generated-file entry: " + relative);
            }

            return full;
        }

        /// <summary>
        /// 同步新生成文件，删除过期生成文件并更新归属记录。
        /// </summary>
        /// <param name="source">本次生成文件的临时目录。</param>
        /// <param name="destination">项目中的输出目录。</param>
        /// <param name="owned">上次生成时登记的相对文件路径。</param>
        /// <param name="extension">受管理文件的扩展名。</param>
        private static void Sync(string source, string destination, List<string> owned, string extension)
        {
            var generated = new List<string>();
            foreach (string file in Directory.GetFiles(source, "*" + extension, SearchOption.AllDirectories))
            {
                string relative = file.Substring(source.Length + 1).Replace('\\', '/');
                string target = OwnedPath(destination, relative, extension);
                Directory.CreateDirectory(Path.GetDirectoryName(target));
                if (!File.Exists(target) || !File.ReadAllBytes(target).SequenceEqual(File.ReadAllBytes(file)))
                {
                    File.Copy(file, target, true);
                }

                generated.Add(relative);
            }

            foreach (string old in owned.Except(generated))
            {
                string target = OwnedPath(destination, old, extension);
                if (File.Exists(target) && !AssetDatabase.DeleteAsset(Path.Combine(destination, old).Replace('\\', '/')))
                {
                    throw new IOException("Could not delete obsolete generated asset: " + target);
                }
            }

            owned.Clear();
            owned.AddRange(generated.OrderBy(p => p, StringComparer.Ordinal));
        }

        /// <summary>
        /// 更新生成数据的运行时清单。
        /// </summary>
        /// <param name="data">数据输出目录。</param>
        /// <param name="schemaHash">表结构版本。</param>
        /// <param name="generatedFiles">生成文件的相对路径，为空时读取目录中的 bytes。</param>
        /// <returns>更新后的数据清单。</returns>
        public static LubanDataTableCatalog WriteCatalog(string data, string schemaHash, IEnumerable<string> generatedFiles = null)
        {
            string path = data + "/Catalog.asset";
            var catalog = AssetDatabase.LoadAssetAtPath<LubanDataTableCatalog>(path);
            if (catalog == null)
            {
                if (File.Exists(path))
                {
                    throw new IOException("Catalog path is occupied: " + path);
                }

                catalog = ScriptableObject.CreateInstance<LubanDataTableCatalog>();
                AssetDatabase.CreateAsset(catalog, path);
            }

            var entries = (generatedFiles ?? Directory.GetFiles(data, "*.bytes").Select(Path.GetFileName)).OrderBy(p => p, StringComparer.Ordinal).Select(relative => new LubanDataTableCatalog.Entry { Name = Path.ChangeExtension(relative, null).Replace('\\', '/'), Data = AssetDatabase.LoadAssetAtPath<TextAsset>(Path.Combine(data, relative).Replace('\\', '/')) }).ToArray();
            if (entries.Length == 0 || entries.Any(entry => entry.Data == null))
            {
                throw new IOException("Generated data assets could not be imported.");
            }

            catalog.SetGeneratedData(schemaHash, Version, entries);
            EditorUtility.SetDirty(catalog);
            AssetDatabase.SaveAssetIfDirty(catalog);
            return catalog;
        }

        /// <summary>
        /// 计算数据的 SHA256 校验值。
        /// </summary>
        /// <param name="bytes">待校验的数据。</param>
        /// <returns>小写十六进制 SHA256 字符串。</returns>
        private static string Hash(byte[] bytes)
        {
            using (var sha = SHA256.Create())
            {
                return BitConverter.ToString(sha.ComputeHash(bytes)).Replace("-", "").ToLowerInvariant();
            }
        }

        /// <summary>
        /// 为进程参数添加双引号并转义内部引号。
        /// </summary>
        /// <param name="value">原始进程参数。</param>
        /// <returns>加引号后的进程参数。</returns>
        private static string Quote(string value)
        {
            return "\"" + value.Replace("\"", "\\\"") + "\"";
        }

        /// <summary>
        /// 运行外部工具并收集输出，超时或异常退出时抛出异常。
        /// </summary>
        /// <param name="executable">工具可执行文件路径。</param>
        /// <param name="arguments">进程参数集合。</param>
        /// <param name="workingDirectory">进程工作目录。</param>
        /// <param name="informationalExitCode">除零之外允许的提示性退出码。</param>
        /// <param name="timeoutMilliseconds">超时时长，以毫秒为单位；非正值时使用默认超时。</param>
        /// <returns>进程标准输出和标准错误的合并文本。</returns>
        private static async Task<string> RunProcess(string executable, IEnumerable<string> arguments, string workingDirectory, int informationalExitCode = 0, int timeoutMilliseconds = 0)
        {
            using (var process = new Process())
            {
                process.StartInfo = new ProcessStartInfo(executable, string.Join(" ", arguments.Select(Quote)))
                {
                    WorkingDirectory = workingDirectory,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    WindowStyle = ProcessWindowStyle.Hidden,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    StandardOutputEncoding = Encoding.UTF8,
                    StandardErrorEncoding = Encoding.UTF8
                };
                if (!process.Start())
                {
                    throw new IOException("Could not start " + executable);
                }

                Task<string> stdout = process.StandardOutput.ReadToEndAsync();
                Task<string> stderr = process.StandardError.ReadToEndAsync();
                int timeout = timeoutMilliseconds > 0 ? timeoutMilliseconds : ProcessTimeoutSeconds * 1000;
                bool exited = await Task.Run(() => process.WaitForExit(timeout));
                if (!exited)
                {
                    process.Kill();
                    await Task.Run(() => process.WaitForExit());
                    throw new TimeoutException(executable + " exceeded the " + timeout + " ms timeout.\n" + await stdout + await stderr);
                }

                string log = await stdout + await stderr;
                if (process.ExitCode != 0 && process.ExitCode != informationalExitCode)
                {
                    throw new IOException(executable + " failed (" + process.ExitCode + "):\n" + log);
                }

                return log;
            }
        }
    }
